// 12. CENTRALIZED AI DOCTOR RECOMMENDATION ENGINE
// ==========================================
export function recommendDoctors(caseContext = {}) {
  const {
    department,
    specialty,
    severity = 'moderate', // 'low' | 'moderate' | 'high' | 'critical'
    budgetPreference, // 'budget' | 'standard' | 'premium'
    location,
    preferredHospitalId,
    patientAge,
    riskLevel = 'standard', // 'low' | 'moderate' | 'high' | 'critical'
    searchQuery,
  } = typeof caseContext === 'string' ? { searchQuery: caseContext } : caseContext;

  const isHighRisk =
    riskLevel === 'high' ||
    riskLevel === 'critical' ||
    severity === 'high' ||
    severity === 'critical';

  // Pool all clinicians: regular doctors + department heads
  const allClinicians = [
    ...doctors.map(d => ({ ...d, isHead: false })),
    ...departmentHeads.map(h => ({
      id: h.id,
      name: h.name,
      title: h.title,
      hospitalId: h.hospitalId,
      hospitalName: h.hospitalName,
      departmentId: h.departmentId,
      departmentName: h.departmentName,
      specialization: h.specialization,
      qualification: h.qualification,
      experience: h.experience,
      experienceYears: h.experienceYears || 15,
      rating: h.rating || 4.9,
      consultationFee: h.consultationFee || 900,
      videoFee: (h.consultationFee || 900) * 0.8,
      status: h.status,
      avatarInitials: h.avatarInitials,
      avatarTone: h.avatarTone,
      description: h.title + ' at ' + h.hospitalName,
      isHead: true,
    })),
  ];

  const scoredCandidates = allClinicians.map(doc => {
    let score = 50;
    const reasons = [];

    // Department / Specialty matching
    if (department) {
      const deptNormalized = department.toLowerCase();
      if (
        doc.departmentName.toLowerCase().includes(deptNormalized) ||
        doc.specialization.toLowerCase().includes(deptNormalized)
      ) {
        score += 30;
        reasons.push(`Specialized in ${doc.departmentName}`);
      }
    }

    if (specialty && doc.specialization.toLowerCase().includes(specialty.toLowerCase())) {
      score += 20;
      reasons.push(`Direct subspecialty match for ${doc.specialization}`);
    }

    if (searchQuery) {
      const q = searchQuery.toLowerCase();
      if (
        doc.name.toLowerCase().includes(q) ||
        doc.departmentName.toLowerCase().includes(q) ||
        doc.specialization.toLowerCase().includes(q) ||
        doc.hospitalName.toLowerCase().includes(q)
      ) {
        score += 25;
      }
    }

    if (location && doc.hospitalName.toLowerCase().includes(location.toLowerCase())) {
      score += 10;
      reasons.push(`Located in ${location}`);
    }

    if (patientAge) {
      if (patientAge < 18 && (doc.departmentName.toLowerCase().includes('pediatric') || doc.specialization.toLowerCase().includes('pediatric'))) {
        score += 20;
        reasons.push('Pediatric specialization matched for patient age');
      } else if (patientAge >= 65 && (doc.departmentName.toLowerCase().includes('general') || doc.specialization.toLowerCase().includes('geriatric'))) {
        score += 15;
        reasons.push('Geriatric/Internal medicine care matched for senior patient');
      }
    }

    // High Severity / Critical Cases: Prioritize clinical experience, tertiary hospital capabilities & top ratings
    if (isHighRisk) {
      if (doc.experienceYears >= 15) {
        score += 25;
        reasons.push(`Senior expert (${doc.experienceYears}+ years experience) prioritized for high-risk triage`);
      } else if (doc.experienceYears >= 10) {
        score += 15;
        reasons.push(`Experienced clinician (${doc.experienceYears} years clinical practice)`);
      }

      if (doc.rating >= 4.9) {
        score += 15;
        reasons.push('Top patient outcome score (4.9+ rating)');
      }

      if (doc.isHead) {
        score += 10;
        reasons.push('Department Leadership & Complex Case Review specialist');
      }

      // Hospital 3 has Level-3 multi-disciplinary emergency infrastructure
      if (doc.hospitalId === 'HOSP-003' || doc.hospitalId === 'HOSP-001') {
        score += 10;
        reasons.push('Affiliated with Level-3 Advanced Tertiary Medical Institute');
      }
    } else {
      // Non-serious / routine cases: Balance reasonable cost, prompt availability, and solid competence
      if (budgetPreference === 'budget' || doc.consultationFee <= 700) {
        score += 20;
        reasons.push('Affordable consultation fee for routine/preventive care');
      } else if (budgetPreference === 'premium' || doc.consultationFee <= 850) {
        score += 10;
        reasons.push('Balanced consultation pricing');
      }

      if (preferredHospitalId && doc.hospitalId === preferredHospitalId) {
        score += 15;
        reasons.push('Preferred local hospital');
      }
    }

    // Cost level evaluation
    let costLevel = 'moderate';
    if (doc.consultationFee <= 650) costLevel = 'budget';
    else if (doc.consultationFee >= 1000) costLevel = 'premium';

    // Cross hospital flag
    const isCrossHospital = preferredHospitalId ? doc.hospitalId !== preferredHospitalId : false;
    if (isCrossHospital && isHighRisk) {
      reasons.push(`Cross-hospital recommendation from ${doc.hospitalName} for specialist excellence`);
    }

    const hospitalObj = hospitals.find(h => h.id === doc.hospitalId);

    return {
      doctor: doc,
      matchScore: Math.min(Math.max(score, 10), 99),
      recommendationReason: reasons.join(' • ') || 'Suited clinician based on overall platform matching',
      costLevel,
      isCrossHospital,
      hospital: hospitalObj,
    };
  });

  // Sort descending by match score
  return scoredCandidates.sort((a, b) => b.matchScore - a.matchScore);
}

