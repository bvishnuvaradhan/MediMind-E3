STAGING_DISCLAIMER = (
    "EXPERIMENTAL STAGING EVALUATION ONLY. This output was generated by an unapproved "
    "candidate model under shadow evaluation. It is NOT a clinical diagnosis and must "
    "NOT be used for patient care or treatment decisions."
)


class StagingDiabetesService:
    """Isolated staging service for shadow evaluation of candidate models."""

    _cached_models: Dict[str, Any] = {}
    _scaler: Optional[Any] = None
    _medians: Optional[Dict[str, float]] = None

    @classmethod
    def is_enabled(cls) -> bool:
        """Check if staging evaluation runtime flag is active.
        
        Fail-closed: Returns True only when ENABLE_STAGING_DIABETES is explicitly 'true' or '1'.
        """
        raw = os.getenv("ENABLE_STAGING_DIABETES", "").strip().lower()
        return raw in ("true", "1")

    @classmethod
    def _verify_artifact_integrity(cls, file_path: Path, filename: str) -> None:
        """Verify SHA-256 hash against trusted provenance manifest before loading."""
        if not file_path.exists():
            raise FileNotFoundError(f"Staging artifact not found: {filename}")

        expected_hash = TRUSTED_ARTIFACT_MANIFEST.get(filename)
        if not expected_hash:
            raise SecurityError(f"Untrusted artifact: {filename} is not in trusted provenance manifest.")

        import hashlib
        computed_hash = hashlib.sha256(file_path.read_bytes()).hexdigest()
        if computed_hash != expected_hash:
            raise PermissionError(
                f"Artifact integrity violation: {filename} hash mismatch. "
                f"Expected {expected_hash}, got {computed_hash}."
            )

    @classmethod
    def load_dependencies(cls) -> None:
        """Load imputation medians and scaler if not already cached.
        
        Enforces feature flag and cryptographic provenance checks before loading.
        """
        if not cls.is_enabled():
            raise PermissionError("Staging diabetes evaluation is disabled (ENABLE_STAGING_DIABETES=false).")

        if cls._medians is None:
            medians_path = EXPERIMENT_DIR / "training_medians.joblib"
            cls._verify_artifact_integrity(medians_path, "training_medians.joblib")
            cls._medians = joblib.load(medians_path)

        if cls._scaler is None:
            scaler_path = EXPERIMENT_DIR / "scaler.joblib"
            cls._verify_artifact_integrity(scaler_path, "scaler.joblib")
            cls._scaler = joblib.load(scaler_path)

    @classmethod
    def load_candidate(cls, candidate_id: str) -> Any:
        """Lazily load a specific candidate model from isolated experiment storage.
        
        Enforces feature flag, candidate whitelist, and SHA-256 verification.
        """
        if not cls.is_enabled():
            raise PermissionError("Staging diabetes evaluation is disabled (ENABLE_STAGING_DIABETES=false).")

        if candidate_id not in CANDIDATE_REGISTRY:
            raise ValueError(f"Unknown staging candidate ID: {candidate_id}. Available: {list(CANDIDATE_REGISTRY.keys())}")

        if candidate_id not in cls._cached_models:
            cls.load_dependencies()
            meta = CANDIDATE_REGISTRY[candidate_id]
            model_file = meta["model_file"]
            model_path = EXPERIMENT_DIR / model_file
            cls._verify_artifact_integrity(model_path, model_file)
            cls._cached_models[candidate_id] = joblib.load(model_path)

        return cls._cached_models[candidate_id]

    @classmethod
    def predict_staging(
        cls,
        request: DiabetesRequest,
        candidate_id: str = "appC_mlp_6layer_bottleneck_gelu",
        enforce_feature_check: bool = True,
    ) -> Dict[str, Any]:
        """Run isolated staging inference without mutating canonical state.

        Args:
            request: Validated DiabetesRequest.
            candidate_id: Identifier of audited staging candidate.
            enforce_feature_check: Verify finite numeric values.

        Returns:
            Dict matching API schema with staging isolation metadata.
        """
        if not cls.is_enabled():
            raise PermissionError("Staging diabetes evaluation is disabled (ENABLE_STAGING_DIABETES=false).")

        # Feature extraction
        values = [getattr(request, f) for f in DIABETES_FEATURES]
        numeric_values = np.asarray(values, dtype=float)
        if enforce_feature_check and not np.isfinite(numeric_values).all():
            raise ValueError("All Diabetes features must be finite numbers.")

        cls.load_dependencies()
        model = cls.load_candidate(candidate_id)
        meta = CANDIDATE_REGISTRY[candidate_id]

        # 1. Biological zero imputation
        frame = pd.DataFrame([numeric_values], columns=DIABETES_FEATURES)
        frame_imputed = apply_biological_zero_imputation(frame, cls._medians)

        # 2. Standard scaling
        scaled_values = cls._scaler.transform(frame_imputed)

        # 3. Model inference
        prob = float(model.predict_proba(scaled_values)[0, 1])
        thresh = meta["threshold"]

        return {
            "risk_probability": round(prob, 4),
            "risk_category": "HIGH" if prob >= thresh else "LOW",
            "threshold": thresh,
            "model_name": f"staging_{candidate_id}",
            "model_version": "staging-0.1.0-exp20261019",
            "candidate_approach": meta["approach"],
            "candidate_description": meta["description"],
            "feature_order": DIABETES_FEATURES,
            "is_staging": True,
            "clinical_approval": False,
            "disclaimer": STAGING_DISCLAIMER,
        }
